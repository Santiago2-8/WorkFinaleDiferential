-- Base de datos del proyecto de predicción de facturas de energía
-- Compatible con el SQL Editor de Supabase.
-- Ejecutar en un proyecto nuevo o después de revisar las tablas existentes.

create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    full_name text,
    created_at timestamptz not null default now()
);

create table if not exists public.bills (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    billing_period_start date not null,
    billing_period_end date,
    consumption_kwh numeric(10,2),
    billed_amount numeric(12,2),
    due_date date,
    source text not null default 'CHEC',
    raw_data jsonb,
    created_at timestamptz not null default now()
);

create table if not exists public.ai_predictions (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    bill_id bigint references public.bills(id) on delete set null,
    predicted_period_start date not null,
    predicted_period_end date,
    predicted_amount numeric(12,2) not null,
    confidence numeric(5,2) check (confidence >= 0 and confidence <= 100),
    explanation text,
    model_version text,
    created_at timestamptz not null default now()
);

create table if not exists public.public_energy_data (
    id bigint generated by default as identity primary key,
    period_start date not null,
    period_end date,
    category text,
    value numeric(12,4),
    unit text,
    source text not null default 'CHEC',
    metadata jsonb,
    created_at timestamptz not null default now()
);

create index if not exists bills_user_id_idx
    on public.bills(user_id);

create index if not exists ai_predictions_user_id_idx
    on public.ai_predictions(user_id);

create index if not exists public_energy_data_period_idx
    on public.public_energy_data(period_start);

-- Crea automáticamente un perfil cuando alguien se registra con Supabase Auth.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
    insert into public.profiles (id)
    values (new.id)
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Activar Row Level Security.
alter table public.profiles enable row level security;
alter table public.bills enable row level security;
alter table public.ai_predictions enable row level security;
alter table public.public_energy_data enable row level security;

-- Eliminar políticas anteriores para poder ejecutar el archivo nuevamente.
drop policy if exists "Users can view their own profile" on public.profiles;
drop policy if exists "Users can update their own profile" on public.profiles;
drop policy if exists "Users can view their own bills" on public.bills;
drop policy if exists "Users can insert their own bills" on public.bills;
drop policy if exists "Users can update their own bills" on public.bills;
drop policy if exists "Users can delete their own bills" on public.bills;
drop policy if exists "Users can view their own predictions" on public.ai_predictions;
drop policy if exists "Public energy data can be read" on public.public_energy_data;

create policy "Users can view their own profile"
on public.profiles for select to authenticated
using (auth.uid() = id);

create policy "Users can update their own profile"
on public.profiles for update to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);

create policy "Users can view their own bills"
on public.bills for select to authenticated
using (auth.uid() = user_id);

create policy "Users can insert their own bills"
on public.bills for insert to authenticated
with check (auth.uid() = user_id);

create policy "Users can update their own bills"
on public.bills for update to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create policy "Users can delete their own bills"
on public.bills for delete to authenticated
using (auth.uid() = user_id);

create policy "Users can view their own predictions"
on public.ai_predictions for select to authenticated
using (auth.uid() = user_id);

create policy "Public energy data can be read"
on public.public_energy_data for select to anon, authenticated
using (true);